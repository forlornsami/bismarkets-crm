/** A readable name for an action code, falling back to "Area: words" for codes without one. */
export function actionLabel(code: string) {
  const known = ACTION_LABEL[code];
  if (known) return known;
  const [area = "", rest = ""] = code.split(".");
  const words = rest.replace(/_/g, " ");
  return `${area.charAt(0).toUpperCase()}${area.slice(1)}: ${words}`;
}
